"""Write docs/EXPLORATORY.md from runs/results_exploratory.json, results_real.json and results_real_bursts.json.
Every number in that file comes from here. usage: python scripts/exploratory_report.py"""
import json
from pathlib import Path

import numpy as np

R = Path("runs")
ex = json.load(open(R / "results_exploratory.json"))
real = json.load(open(R / "results_real.json"))
rb = json.load(open(R / "results_real_bursts.json"))
f = lambda x, d=3: f"{x:.{d}f}"
sg = lambda x: ("+" if x >= 0 else "−") + f"{abs(x):.3f}"

order = [f"{m}_N{N}" for N in (5, 10, 20) for m in ("learned", "fixed", "random", "entropy", "velocity")] + \
        ["exp_refractory_N10", "abl_object_N10", "abl_conv_N10"]
names = {"exp_refractory_N10": "refractory router (r = 3), N10", "abl_object_N10": "learned + object state, N10",
         "abl_conv_N10": "learned, conv encoder, N10"}

L = ["# Exploratory analyses (NOT pre-registered)", "",
     "Generated by `scripts/exploratory_report.py`. None of this changes the H1–H4 verdicts; it is reported separately.",
     "Simulated test split (300 episodes), mean over seeds (number of seeds in brackets).", "",
     "## 1. Chance-corrected and burst-merged boundary F1", "",
     "Chance = mean F1 of the same boundaries shuffled within each episode (same count, 1,000 shuffles). "
     "For Fixed, *grid chance* = the same every-N grid from a random offset per episode. "
     "Burst-merged = a boundary is kept only if it is ≥ 3 steps after the last kept one (post hoc).", "",
     "| method | rate | F1 ±1 | chance ±1 | F1 − chance ±1 | F1 ±3 | chance ±3 | F1 − chance ±3 | grid chance ±3 | merged F1 ±1 | merged F1 ±3 |",
     "|---|---|---|---|---|---|---|---|---|---|---|"]
for k in order:
    if k not in ex:
        continue
    m, n = ex[k]["mean"], len(ex[k]["runs"])
    gc = f(m["grid_chance_F1_tol3"]) if "grid_chance_F1_tol3" in m else "–"
    L.append(f"| {names.get(k, k.replace('_', ', '))} ({n}) | {f(m['rate'])} | {f(m['F1_tol1'])} | {f(m['chance_F1_tol1'])} | "
             f"**{sg(m['F1_minus_chance_tol1'])}** | {f(m['F1_tol3'])} | {f(m['chance_F1_tol3'])} | "
             f"**{sg(m['F1_minus_chance_tol3'])}** | {gc} | {f(m['merged_F1_tol1'])} | {f(m['merged_F1_tol3'])} |")
rf = ex["exp_refractory_N10"]
L += ["", "Refractory router, F1 − chance (±3) per seed: " +
      ", ".join(f"{rid.rsplit('_', 1)[1]} {sg(v['F1_minus_chance_tol3'])}" for rid, v in rf["runs"].items()) + ".",
      "",
      "## 2. Boundary density by phase (boundaries per step; step 0 excluded)", "",
      "| method | " + " | ".join(ex["_true"]["phase_density"]) + " |", "|---|" + "---|" * len(ex["_true"]["phase_density"])]
L.append("| true phase starts | " + " | ".join(f(v) for v in ex["_true"]["phase_density"].values()) + " |")
for k in order:
    if k in ex:
        L.append(f"| {names.get(k, k.replace('_', ', '))} | " + " | ".join(f(v) for v in ex[k]["mean"]["phase_density"].values()) + " |")

L += ["", "## 3. How the refractory window was chosen", "",
      "The refractory router was added to the pre-registration (commit `1f1faa0`, 2026-10-29 14:08) as an exploratory "
      "variant, motivated by the pilot burst pattern (pilot v1: 58–67% of gaps between learned boundaries were 1 step). "
      "The window r = 3 was set once, by hand, with no sweep and no refractory pilot run; no other value was ever trained. "
      "The decision log records the motivation but no explicit reason for 3. It equals the ±3 tolerance of the primary F1, "
      "which matters: one-to-one matching counts extra boundaries within ±3 of one true boundary as false positives, and "
      "a 3-step refractory period removes exactly those. The ±1 numbers above are the check that the gain is not only that.",
      "", "## 4. Burst locations on the real-robot test episodes", "",
      "Burst = maximal run of boundaries with gaps < 3 steps. A burst is *at grasp / at release* if its span comes within ±3 "
      "steps of that gripper event (a long burst touching an event counts all its boundaries there); otherwise it is placed "
      "by position (start = within the first 5 steps; reach = before the first grasp; transport = between grasp and last "
      "release; retreat = after it). Event recall = share of gripper events with a boundary within ±3 steps.", ""]
regions = ["start", "reach", "at_grasp", "transport", "at_release", "retreat"]
for name, r in rb.items():
    L += [f"**{name}** — {r['n_test_episodes']} test episodes, {r['n_events']} gripper events.", "",
          "| run | bursts | boundaries | mean burst length | 1-step gaps | event recall | " +
          " | ".join(f"% {x.replace('_', ' ')}" for x in regions) + " |", "|" + "---|" * (6 + len(regions))]
    for rid, d in r["runs"].items():
        if "_learned_" not in rid:
            continue
        sh = d["boundary_share_by_region"]
        L.append(f"| {rid} | {d['n_bursts']} | {d['n_boundaries']} | {d['mean_burst_len']:.1f} | {d['share_1step_gaps']:.2f} | "
                 f"{d['event_recall']:.2f} | " + " | ".join(f"{100 * sh[x]:.0f}" for x in regions) + " |")
    L.append("")

kc, so = real["koch"]["entropy_alignment"], real["so100"]["entropy_alignment"]
ke = rb["koch"]["runs"]["real_koch_entropy_N12_s0"]
se = rb["so100"]["runs"]["real_so100_entropy_N12_s0"]
kf = rb["koch"]["runs"]["real_koch_fixed_N12_s0"]
kl = real["koch"]["H3"]
L += ["## 5. Practical finding: a surprise-based rule marks gripper events", "",
      f"On Koch, the entropy rule (boundary where a small GRU's next-step surprise is above a threshold fitted for rate 1/12) "
      f"puts {100 * kc['share']:.0f}% of its boundaries within ±3 steps (0.1 s) of a gripper open/close event, "
      f"{kc['ratio']:.1f}× the within-episode shuffle (p = {kc['p']:.3f}, the smallest possible with 1,000 shuffles). "
      f"It has a boundary within ±3 steps of {round(ke['event_recall'] * rb['koch']['n_events'])} of the "
      f"{rb['koch']['n_events']} test events, using {ke['n_boundaries']} boundaries; the Fixed rule ({kf['n_boundaries']} "
      f"boundaries) reaches {round(kf['event_recall'] * rb['koch']['n_events'])}. The learned router reaches "
      f"{kl['ratio']:.2f}× on the same episodes.", "",
      f"It does **not** replicate at that strength on SO-100: {so['ratio']:.2f}× chance (p = {so['p']:.3f}), event recall "
      f"{se['event_recall']:.2f}. There the threshold, fitted on only 5 validation episodes, gave far too many boundaries "
      f"(test compression {json.load(open(R / 'real_so100_entropy_N12_s0' / 'metrics.json'))['test_compression']:.2f} "
      f"for a target of 12), "
      f"and {100 * se['boundary_share_by_region']['at_release']:.0f}% of them sit in bursts at the release.", "",
      "Caveats: one proxy model per dataset, so the three entropy \"seeds\" are identical; "
      f"{rb['koch']['n_test_episodes']} and {rb['so100']['n_test_episodes']} test episodes; the threshold is fitted on very "
      "few validation episodes. As a practical tool — flagging grasp and release moments in teleoperation logs without "
      "labels — the result is promising on one dataset, not established."]
Path("docs/EXPLORATORY.md").write_text("\n".join(L) + "\n")
print("docs/EXPLORATORY.md written")
