"""Stage the Hugging Face upload in hf_stage/ (git-ignored): one model repo (checkpoints of every simulated-data and
Part B run) and one dataset repo (the simulated data generated here, plus the result files). Real-robot checkpoints and
the LeRobot datasets are not included. Every staged text file is scanned with scripts/check_sensitive.py rules.
usage: python scripts/stage_hf.py <hf-username>"""
import shutil
import sys
from pathlib import Path

sys.path.insert(0, "scripts")
from check_sensitive import scan_text  # noqa: E402

USER = sys.argv[1]
GH = "https://github.com/NapoleonPK/robochunk-study"
ST = Path("hf_stage")
RUN_PREFIX = ("sim_", "exp_", "abl_", "v2_sim_", "partb_", "proxy_sim")
KEEP = ("best.pt", "config.yaml", "norm.json", "metrics.json", "history.json", "git.txt")
CREDIT = ("The model follows **H-Net** (Sukjun Hwang, Brandon Wang, Albert Gu, *Dynamic Chunking for End-to-End "
          "Hierarchical Sequence Modeling*, arXiv:2507.07955) and Cartesia's posts on dynamic chunking. Independent "
          "re-implementation for robot trajectories, not affiliated with the H-Net authors or Cartesia. Simulation: "
          "Gymnasium-Robotics and MuJoCo.")

MODEL_CARD = f"""---
license: mit
tags: [robotics, h-net, dynamic-chunking, behaviour-cloning, pre-registered]
library_name: pytorch
---
# RoboChunk checkpoints

Checkpoints from **RoboChunk**, a pre-registered study of H-Net-style dynamic chunking on robot trajectories
(FetchPickAndPlace-v4 with a scripted expert). Code, pre-registration, full results and figures: **{GH}**
(see `REPORT.md`).

Author: Téo Tran Van Lieu.

## Contents
`runs/<run_id>/` for every simulated-data and Part B run:
- `best.pt` — PyTorch state dict at the best validation epoch (load with `robochunk.train.build_model` and the run's
  `config.yaml`, as in `scripts/analyze_v2.py`).
- `config.yaml`, `norm.json` (input normalisation), `metrics.json` (test metrics, stop reason), `history.json`
  (training curve), `git.txt` (code commit at training time; the history was rewritten once before publication, so map
  it with `docs/commit-map.txt` in the GitHub repository).

Run ids: `sim_<method>_N<N>_s<seed>` (main study), `exp_refractory_N10_s*` (exploratory refractory router),
`v2_sim_refractory_N10_s3–5` (v2 secondary seeds), `abl_*` (ablations), `partb_*` (models trained on the Part B
reference set R for novelty scoring), `proxy_sim` (entropy-baseline proxy). Real-robot checkpoints are not published.

## Results in one line
The plain learned router does not find motion phases (H1 failed) but predicts better than fixed chunking (H2 passed);
the refractory variant's chance-corrected advantage replicated on fresh data; novelty predicted policy gain on clean data
but ranked corrupted data as most novel. Numbers and caveats: `REPORT.md` in the GitHub repository.

## Credits
{CREDIT}
"""

DATA_CARD = f"""---
license: cc-by-4.0
tags: [robotics, simulation, pick-and-place, motion-segmentation, mujoco]
pretty_name: RoboChunk simulated pick-and-place trajectories
size_categories: [1K<n<10K]
---
# RoboChunk simulated data and results

Simulated pick-and-place trajectories generated for **RoboChunk** ({GH}), with ground-truth motion-phase labels, plus the
study's result files. All data here was generated by the study's own scripted expert; no third-party data is included.

Author: Téo Tran Van Lieu.

## Contents
- `sim/` — `train`, `val`, `test`, `fresh` (v2 test set), `pilot` splits. FetchPickAndPlace-v4 (MuJoCo 3.3.7), 25 Hz,
  7 labelled phases (approach, descend, close, lift, transport, open, retreat), action noise, pauses and occasional
  grasp retries. Regenerate exactly with `python scripts/make_sim_data.py`.
- `partb/` — Part B reference set `R`, `R_heldout`, `R_val`, clean candidates `C1–C11` and corrupted candidates
  `X1–X4` (`python scripts/make_partb_data.py`). What each candidate is: `DECISIONS.md` in the GitHub repository.
- `results/` — every result file the report is generated from (`results_*.json`, `partb_*.json`, summary CSVs) and the
  per-episode policy successes behind H4 (`partb_policy*/`).

Files are NumPy `.npz` archives readable with `robochunk.data_sim.load`. Generator details and splits by seed:
`DECISIONS.md` and `robochunk/data_sim.py`.

## Credits
{CREDIT}
"""


def main():
    if ST.exists():
        shutil.rmtree(ST)
    m, d = ST / "model", ST / "dataset"
    for run in sorted(Path("runs").iterdir()):
        if run.is_dir() and run.name.startswith(RUN_PREFIX) and (run / "best.pt").exists():
            for f in KEEP:
                if (run / f).exists():
                    (m / "runs" / run.name).mkdir(parents=True, exist_ok=True)
                    shutil.copy2(run / f, m / "runs" / run.name / f)
    (m / "README.md").write_text(MODEL_CARD)
    for sub in ("sim", "partb"):
        shutil.copytree(Path("data") / sub, d / sub)
    (d / "results").mkdir(parents=True)
    for f in list(Path("runs").glob("results_*.json")) + list(Path("runs").glob("partb_*.json")) + \
            list(Path("runs").glob("summary*.csv")):
        shutil.copy2(f, d / "results" / f.name)
    for sub in ("partb_policy", "partb_policy_matched"):  # per-episode 0/1 policy successes behind H4
        shutil.copytree(Path("runs") / sub, d / "results" / sub)
    (d / "README.md").write_text(DATA_CARD)
    bad = []
    for f in ST.rglob("*"):
        if f.is_file() and f.suffix in (".md", ".yaml", ".json", ".txt", ".csv"):
            bad += scan_text(str(f), f.read_text(errors="replace"))
            if "/Users/" in f.read_text(errors="replace"):
                bad.append(f"{f}: local path")
    assert not bad, bad
    n_runs = len(list((m / "runs").iterdir()))
    size = sum(f.stat().st_size for f in ST.rglob("*") if f.is_file()) / 1e9
    print(f"staged {n_runs} runs + dataset for {USER}; {size:.2f} GB; sensitive scan ok")


if __name__ == "__main__":
    main()
