      f"{REAL['so100']['entropy_alignment']['ratio']:.2f}×. SO-101 (v2 secondary): {es['ratio']:.2f}× (p = {es['p']:.3f}), "
      f"event recall {es['event_recall']:.3f}. Promising on two of three datasets, each with 5–10 test episodes.",
