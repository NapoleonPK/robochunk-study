for d, nm in (("so100", "SO-100"), ("koch", "Koch"), ("so101", "SO-101 (fresh)")):
    t = Q2[d]["test"]
    L.append(f"| {nm} | {Q2[d]['n_test_episodes']} | {Q2[d]['n_events']} | {t['ratio']:.2f}× | {t['p']:.3f} | " +
             ", ".join(f"{v['event_recall']:.2f}" for v in Q2[d]["runs"].values()) + " | " +
             ", ".join(Q2[d]["stops"].values()) + " |")
