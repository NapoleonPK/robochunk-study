h3s, h3k = REAL["so100"]["H3"], REAL["koch"]["H3"]
h4 = B["h4"]
rc = BP["rho_ci"]
RATIOS = [REAL[d]["H3"]["ratio"] for d in ("so100", "koch")] + [Q2[d]["test"]["ratio"] for d in ("so100", "koch", "so101")]

