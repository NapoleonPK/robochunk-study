"""Write REPORT.md from the result files in runs/. Every number in the report comes from here; nothing is typed by hand.
usage: python scripts/make_report.py"""
import glob
import json
from pathlib import Path

R = Path("runs")
A = json.load(open(R / "results_partA.json"))
REAL = json.load(open(R / "results_real.json"))
RB = json.load(open(R / "results_real_bursts.json"))
B = json.load(open(R / "results_partB.json"))
BP = json.load(open(R / "results_partB_posthoc.json"))
BM = json.load(open(R / "results_partB_matched.json"))
EX = json.load(open(R / "results_exploratory.json"))
V2 = json.load(open(R / "results_v2.json"))
S2, Q2 = V2["sim"], V2["real"]

